// scripts/campus-distances.mjs
// Measures the walking distance from every food spot to every delivery point
// in functions/src/campus.ts, on OpenStreetMap footpaths (the public OSRM
// "foot" router run by FOSSGIS: routing.openstreetmap.de), and writes
// functions/src/campusDistances.ts, which the fee calculation uses.
//
// Run after adding or moving a place in campus.ts:
//   cd functions && npm run build && cd .. && node scripts/campus-distances.mjs
// Then build again, check the fee table it prints, and commit both files.
// Places without a position (source 'missing') are skipped; they are priced
// at FALLBACK_DELIVERY_FEE_JMD until they get one.
//
// Each distance is the router's footpath route PLUS the two short stretches
// from each pin to the nearest mapped path (the router leaves those out),
// then capped at MAX_WALK_DETOUR × the straight line, so a shortcut missing
// from the map can't overcharge a student. Capped routes are listed in
// CAMPUS_ROUTES.md with Google Maps walking links to check by hand.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { DROP_POINTS, PICKUP_POINTS } = require(path.join(root, 'functions/lib/campus.js'));
const { deliveryFeeForDistance, splitDeliveryFee, MAX_WALK_DETOUR } = require(path.join(root, 'functions/lib/shared.js'));

const rad = d => (d * Math.PI) / 180;
function straightM(a, b) {
  const dLat = rad(b.latitude - a.latitude);
  const dLng = rad(b.longitude - a.longitude);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.latitude)) * Math.cos(rad(b.latitude)) * Math.sin(dLng / 2) ** 2;
  return 2 * 6371000 * Math.asin(Math.min(1, Math.sqrt(h)));
}

const placed = list => list.filter(x => typeof x.latitude === 'number' && typeof x.longitude === 'number');
const pickups = placed(PICKUP_POINTS);
const drops = placed(DROP_POINTS);

const coords = [...pickups, ...drops].map(x => `${x.longitude},${x.latitude}`).join(';');
const sources = pickups.map((_, i) => i).join(';');
const destinations = drops.map((_, i) => i + pickups.length).join(';');
const url = `https://routing.openstreetmap.de/routed-foot/table/v1/foot/${coords}` +
  `?sources=${sources}&destinations=${destinations}&annotations=distance`;

const res = await fetch(url, { headers: { 'User-Agent': 'DormDash campus-distances (jcommerceandtech@gmail.com)' } });
const json = await res.json();
if (json.code !== 'Ok') throw new Error(`Router said ${json.code}: ${json.message ?? ''}`);

const walk = {};
const capped = [];
pickups.forEach((from, i) => {
  walk[from.id] = {};
  drops.forEach((to, j) => {
    const route = json.distances[i][j];
    if (typeof route !== 'number') return;
    // The router snaps each pin to the nearest path; add those two stretches back.
    const full = route + (json.sources[i].distance ?? 0) + (json.destinations[j].distance ?? 0);
    const straight = straightM(from, to);
    const cap = straight * MAX_WALK_DETOUR;
    if (full > cap && straight > 50) capped.push({ from, to, full, straight, cap });
    walk[from.id][to.id] = Math.round(Math.min(full, Math.max(cap, straight)));
  });
});

const body = JSON.stringify(walk, null, 2).replace(/"([a-z0-9-]+)":/g, (_, k) => /^[a-z]\w*$/.test(k) ? `${k}:` : `'${k}':`);
writeFileSync(path.join(root, 'functions/src/campusDistances.ts'),
`// functions/src/campusDistances.ts
// GENERATED by scripts/campus-distances.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Walking distance in metres from each food spot to each delivery point
// (functions/src/campus.ts), measured on OpenStreetMap footpaths.
export const WALK_M: Record<string, Record<string, number>> = ${body};
`);

// Routes the cap shortened: check these on the ground or in Google Maps.
const gmaps = (a, b) => `https://www.google.com/maps/dir/?api=1&origin=${a.latitude},${a.longitude}&destination=${b.latitude},${b.longitude}&travelmode=walking`;
capped.sort((a, b) => b.full / b.straight - a.full / a.straight);
writeFileSync(path.join(root, 'CAMPUS_ROUTES.md'), `# Routes to check

Generated by \`scripts/campus-distances.mjs\`. These ${capped.length} routes came out more than ${MAX_WALK_DETOUR}× the straight-line distance on the OpenStreetMap footpath map, usually because a shortcut students really use isn't on the map. Each is priced at ${MAX_WALK_DETOUR}× the straight line instead, so students aren't overcharged. If Google Maps (or walking it) shows the real route is longer, send me the route and the real distance and I'll set it.

| Food spot | Place | Straight line | Map route | Priced as | Fee now | Check |
|---|---|---|---|---|---|---|
${capped.map(c => `| ${c.from.name} | ${c.to.name} | ${Math.round(c.straight)} m | ${Math.round(c.full)} m | ${Math.round(c.cap)} m | J$${deliveryFeeForDistance(c.cap)} (map route: J$${deliveryFeeForDistance(c.full)}) | [walking directions](${gmaps(c.from, c.to)}) |`).join('\n')}
`);

// A quick look at what students will pay.
const fees = {};
for (const from of pickups) for (const to of drops) {
  const fee = deliveryFeeForDistance(walk[from.id][to.id]);
  fees[fee] = (fees[fee] ?? 0) + 1;
}
console.log(`Wrote ${pickups.length} food spots × ${drops.length} delivery points (${capped.length} routes capped at ${MAX_WALK_DETOUR}× the straight line; see CAMPUS_ROUTES.md).`);
console.log('Fee  Dasher  DormDash  Pairs');
for (const fee of Object.keys(fees).map(Number).sort((a, b) => a - b)) {
  const s = splitDeliveryFee(fee);
  console.log(`${String(fee).padEnd(5)}${String(s.dasherPayoutJmd).padEnd(8)}${String(s.platformFeeJmd).padEnd(10)}${fees[fee]}`);
}
